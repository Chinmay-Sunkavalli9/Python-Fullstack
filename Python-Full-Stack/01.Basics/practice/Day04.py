# Set Example
colors = {"Red", "Blue", "Green", "Red"}
print(colors)
print(type(colors))

# Dictionary Example
student = {
    "name": "Chinmay",
    "age": 20,
    "course": "Python"
}
print(student)
print(student["name"])
print(student["course"])

# Boolean Example
a = 10
b = 20
print(a < b)
print(a > b)

# None Example
value = None
print(value)
print(type(value))

# Type Casting
a = 25
print(float(a))
print(str(a))
print(bool(a))

# String to Integer
num = "100"
print(int(num))
print(float(num))
print(bool(num))

