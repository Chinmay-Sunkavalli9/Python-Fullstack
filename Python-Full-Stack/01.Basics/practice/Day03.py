# List
fruits = ["Apple", "Mango", "Orange"]
print(fruits)
print(fruits[1])

# Tuple
colors = ("Red", "Blue", "Green")
print(colors)
print(type(colors))

# Range
print(list(range(1, 6)))

# Swapping
a = 15
b = 25
a, b = b, a
print(a, b)

# Swapping (Using Third Variable)
x = 50
y = 100
temp = x
x = y
y = temp
print(x, y)